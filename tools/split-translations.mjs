// tools/split-translations.mjs: splits translations.js (the one place all site wording lives, all 10 languages,
// ~650 KB) into one small file per language in i18n/, so a page downloads only the language it shows.
//   i18n/en.js  English, loaded by every page (it is also the fallback for any missing key), plus the list of
//               the other files and their versions (window.TSE_I18N)
//   i18n/ja.js, i18n/ko.js ... fetched by app.js only when that language is picked (or saved / the browser's)
// Keep editing translations.js (by hand or in the Tenshi Editor); never edit i18n/ by hand. To add keys (e.g. new
// Japanese copy), add them to the right language block in translations.js and run `npm run build`
// (stamp-assets.mjs runs this first; the Editor's rebuild Action does it after every text save).
// Run from the repository folder: node tools/split-translations.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from "node:fs";
import { createHash } from "node:crypto";
import vm from "node:vm";

export function splitTranslations() {
  const sandbox = { window: {} };
  vm.runInNewContext(readFileSync("translations.js", "utf8"), sandbox);
  const T = sandbox.window.TRANSLATIONS;
  if (!T || !T.en) throw new Error("translations.js: no window.TRANSLATIONS.en");
  mkdirSync("i18n", { recursive: true });
  const hash = (s) => createHash("sha256").update(s).digest("hex").slice(0, 8);
  const head = "// Generated by tools/split-translations.mjs from translations.js. Edit translations.js, not this file.\n";
  const body = (lang) => `(window.TRANSLATIONS = window.TRANSLATIONS || {})[${JSON.stringify(lang)}] = ${JSON.stringify(T[lang])};\n`;
  const versions = {};
  const langs = Object.keys(T);
  for (const lang of langs) {
    if (lang === "en") continue;
    const text = head + body(lang);
    versions[lang] = hash(text);
    writeFileSync(`i18n/${lang}.js`, text);
  }
  writeFileSync("i18n/en.js", head + `window.TSE_I18N = ${JSON.stringify({ langs, v: versions })};\n` + body("en"));
  // Drop files of languages that were removed from translations.js.
  for (const f of readdirSync("i18n")) if (f.endsWith(".js") && !langs.includes(f.slice(0, -3))) unlinkSync("i18n/" + f);
  return { langs, versions };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { langs } = splitTranslations();
  console.log(`i18n/: ${langs.length} language files written`);
}
